#![forbid(unsafe_code)]
//! Pure safe IPv4/UDP packet builder and `nftables` / `ip xfrm` script generators.
//!
//! No hard-coded lab IP addresses: every rule is generated strictly from the caller's
//! peer directory (`IkeProxyConfig`).

use std::net::Ipv4Addr;

use crate::config::IkeProxyConfig;
use crate::config::ProxyError;

/// Standard RFC 791 one's-complement IPv4 header checksum.
#[must_use]
pub fn ipv4_header_checksum(header: &[u8]) -> u16 {
    let mut sum: u32 = 0;
    let mut chunks = header.chunks_exact(2);
    for chunk in &mut chunks {
        sum += u32::from(u16::from_be_bytes([chunk[0], chunk[1]]));
    }
    if let Some(&last) = chunks.remainder().first() {
        sum += u32::from(last) << 8;
    }
    while (sum >> 16) != 0 {
        sum = (sum & 0xffff) + (sum >> 16);
    }
    !(sum as u16)
}

/// Crafts a raw IPv4 + UDP datagram for transparent local injection into `charon` (`ike_proxy.py::_raw_inject_ipv4_udp`).
///
/// Sets UDP checksum to `0` (explicitly valid per RFC 768 for IPv4) and preserves
/// `src_ip:src_port` -> `dst_ip:dst_port` without binding the already-owned `:500`/`:4500` socket.
pub fn build_ipv4_udp_packet(
    src_ip: Ipv4Addr,
    src_port: u16,
    dst_ip: Ipv4Addr,
    dst_port: u16,
    ip_id: u16,
    payload: &[u8],
) -> Result<Vec<u8>, ProxyError> {
    let udp_len = 8usize
        .checked_add(payload.len())
        .ok_or(ProxyError::InvalidPacket("udp_len_overflow"))?;
    let ip_len = 20usize
        .checked_add(udp_len)
        .ok_or(ProxyError::InvalidPacket("ip_len_overflow"))?;
    if ip_len > u16::MAX as usize {
        return Err(ProxyError::InvalidPacket("packet_exceeds_ipv4_max"));
    }

    let mut pkt = Vec::with_capacity(ip_len);
    // IPv4 header (20 bytes, IHL=5, TTL=64, proto=UDP=17)
    pkt.push(0x45);
    pkt.push(0x00);
    pkt.extend_from_slice(&(ip_len as u16).to_be_bytes());
    pkt.extend_from_slice(&ip_id.to_be_bytes());
    pkt.extend_from_slice(&0u16.to_be_bytes()); // flags & fragment offset
    pkt.push(64); // TTL
    pkt.push(17); // IPPROTO_UDP
    pkt.extend_from_slice(&0u16.to_be_bytes()); // checksum placeholder
    pkt.extend_from_slice(&src_ip.octets());
    pkt.extend_from_slice(&dst_ip.octets());

    let csum = ipv4_header_checksum(&pkt[..20]);
    pkt[10..12].copy_from_slice(&csum.to_be_bytes());

    // UDP header (8 bytes, checksum = 0 valid in IPv4)
    pkt.extend_from_slice(&src_port.to_be_bytes());
    pkt.extend_from_slice(&dst_port.to_be_bytes());
    pkt.extend_from_slice(&(udp_len as u16).to_be_bytes());
    pkt.extend_from_slice(&0u16.to_be_bytes());

    pkt.extend_from_slice(payload);
    Ok(pkt)
}

/// Generates a parameterized `nftables` ruleset redirecting ONLY IKEv2 control traffic
/// (UDP/500 and UDP/4500 with Non-ESP Marker `00 00 00 00`) while letting ESP and marked
/// injected packets (`SO_MARK`) bypass cleanly.
#[must_use]
pub fn render_nftables_rules(config: &IkeProxyConfig) -> String {
    let mut out = String::new();
    let mark_hex = format!("0x{:x}", config.socket_mark);
    out.push_str("#!/usr/bin/env bash\nset -euo pipefail\n\n");
    out.push_str("# Generated by cco-linux-proxy: redirect IKEv2 control only, never ESP.\n");
    out.push_str("sysctl -w net.ipv4.ip_nonlocal_bind=1 >/dev/null || true\n");
    out.push_str("sysctl -w net.ipv4.conf.all.accept_local=1 >/dev/null || true\n");
    out.push_str("sysctl -w net.ipv4.conf.all.rp_filter=0 >/dev/null || true\n");
    out.push_str("sysctl -w net.ipv4.conf.default.rp_filter=0 >/dev/null || true\n");
    out.push_str("for f in /proc/sys/net/ipv4/conf/*/rp_filter; do echo 0 > \"$f\" 2>/dev/null || true; done\n\n");
    out.push_str(
        "nft list table inet ikeproxy >/dev/null 2>&1 && nft delete table inet ikeproxy\n",
    );
    out.push_str("nft -f - <<'NFT'\n");
    out.push_str("add table inet ikeproxy\n");
    out.push_str("add chain inet ikeproxy output_raw { type filter hook output priority raw; policy accept; }\n");
    out.push_str(
        "add chain inet ikeproxy output { type nat hook output priority -100; policy accept; }\n",
    );
    out.push_str(&format!(
        "add rule inet ikeproxy output_raw meta mark {mark_hex} notrack\n"
    ));
    out.push_str(&format!(
        "add rule inet ikeproxy output meta mark {mark_hex} return\n"
    ));

    for spec in &config.capture_specs {
        let Some(ref peer_name) = spec.dst_user_hint else {
            continue;
        };
        let Some(&peer_ip) = config.peer_ips.get(peer_name) else {
            continue;
        };
        if spec.ike_port == 500 {
            out.push_str(&format!(
                "add rule inet ikeproxy output ip daddr {peer_ip} udp dport 500 redirect to :{}\n",
                spec.capture_port
            ));
        } else if spec.ike_port == 4500 {
            // Non-ESP Marker (first 4 bytes of UDP payload at @th,64,32 == 0x00000000);
            // ESP-in-UDP has a non-zero SPI and bypasses the redirect directly!
            out.push_str(&format!(
                "add rule inet ikeproxy output ip daddr {peer_ip} udp dport 4500 @th,64,32 0x00000000 redirect to :{}\n",
                spec.capture_port
            ));
        }
    }
    out.push_str("NFT\n");
    out
}

/// Generates `ip xfrm policy` bypass rules keeping the overlay UDP control port outside
/// IPsec host-to-host `CHILD_SA` policies (essential for repeated-role routes like `A->B->A->B`).
#[must_use]
pub fn render_xfrm_bypass_script(
    config: &IkeProxyConfig,
    overlay_port: u16,
    priority: u32,
) -> String {
    let mut out = String::new();
    out.push_str("#!/usr/bin/env bash\nset -euo pipefail\n\n");
    out.push_str(&format!(
        "# XFRM bypass for overlay UDP/{overlay_port} on {} ({})\n",
        config.local_node, config.local_ip
    ));
    for (peer_name, &peer_ip) in &config.peer_ips {
        if peer_name == &config.local_node {
            continue;
        }
        out.push_str(&format!(
            "ip xfrm policy delete dir out src {}/32 dst {peer_ip}/32 proto udp sport {overlay_port} dport {overlay_port} 2>/dev/null || true\n",
            config.local_ip
        ));
        out.push_str(&format!(
            "ip xfrm policy add dir out src {}/32 dst {peer_ip}/32 proto udp sport {overlay_port} dport {overlay_port} action allow priority {priority}\n",
            config.local_ip
        ));
        out.push_str(&format!(
            "ip xfrm policy delete dir in src {peer_ip}/32 dst {}/32 proto udp sport {overlay_port} dport {overlay_port} 2>/dev/null || true\n",
            config.local_ip
        ));
        out.push_str(&format!(
            "ip xfrm policy add dir in src {peer_ip}/32 dst {}/32 proto udp sport {overlay_port} dport {overlay_port} action allow priority {priority}\n",
            config.local_ip
        ));
    }
    out
}
